// Writes lib/trade/registry-chains.ts: the viem chain definitions the sponsored
// EVM registry names, imported one by one.
//
//   node scripts/gen-registry-chains.mjs
//
// Why generated: `import * as chains from "viem/chains"` looked up by a key
// read from JSON cannot be tree-shaken, so the whole catalogue — every chain
// viem knows, ~130 kB gzipped — shipped with any route that touched the
// registry. When the session providers began reading it for the kit's RPC
// list, that meant EVERY signed-in route, /auth and /interests included.
// Named imports of just the chains the registry lists are tree-shaken to those
// chains. lib/trade/registry-chains.test.ts fails when this file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const registry = JSON.parse(
  readFileSync(join(root, "config/alchemy-bso-evm-networks.json"), "utf8")
);

export function render(entries) {
  const keys = [...new Set(entries.map((e) => e.chainKey).filter(Boolean))].sort();
  return [
    "// GENERATED by scripts/gen-registry-chains.mjs from config/alchemy-bso-evm-networks.json.",
    "// Do not edit: run `pnpm registry:chains` after changing the registry.",
    "//",
    "// The viem chains the sponsored EVM registry names, imported by name so the",
    "// bundler keeps these and drops the rest of viem's catalogue (see the script).",
    "import {",
    ...keys.map((k) => `  ${k},`),
    '} from "viem/chains";',

    "",
    "export const REGISTRY_CHAINS = {",
    ...keys.map((k) => `  ${k},`),
    "} as const;",
    "",
  ].join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = join(root, "lib/trade/registry-chains.ts");
  writeFileSync(out, render(registry));
  console.log(`wrote ${out}`);
}
